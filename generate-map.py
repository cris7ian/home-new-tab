#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["shapely==2.1.2"]
# ///
"""Regenerate src/map.svg: uv run --script generate-map.py [--output PATH].

Inputs are local, gzip-compressed copies of Natural Earth v5.1.2 (public domain):
https://github.com/nvkelso/natural-earth-vector/tree/v5.1.2/geojson
The timezone layer depicts the source's nominal UTC-offset boundaries, not
live daylight-saving rules. No network access is needed once Shapely is installed.
"""

import argparse
from collections import defaultdict
import gzip
import json
from pathlib import Path

from shapely import box, union_all
from shapely.geometry import shape
from shapely.ops import linemerge


ROOT = Path(__file__).resolve().parent
FRAME = box(-180, -80, 180, 85)
SIMPLIFY = 0.09  # degrees; under 0.2 SVG units at the output scale


def parts(geometry, kind):
    if geometry.is_empty:
        return
    if geometry.geom_type == kind:
        yield geometry
    elif hasattr(geometry, "geoms"):
        for child in geometry.geoms:
            yield from parts(child, kind)


def features(stem):
    with gzip.open(ROOT / f"{stem}.geojson.gz", "rt", encoding="utf-8") as source:
        return json.load(source)["features"]


def number(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def project(lon, lat):
    return f"{number((lon + 180) * 2)} {number((85 - lat) * 2)}"


def path_data(coords, closed=False):
    points = [project(lon, lat) for lon, lat in coords]
    if closed:
        points.pop()
    # Simplification and output rounding can leave adjacent equal points.
    points = [p for i, p in enumerate(points) if i == 0 or p != points[i - 1]]
    if len(set(points)) < (3 if closed else 2):
        return ""
    return "M" + " ".join(points) + ("Z" if closed else "")


def line_paths(geometry, tolerance=0):
    merged = linemerge(list(parts(geometry, "LineString")))
    paths = []
    for line in parts(merged, "LineString"):
        line = line.simplify(tolerance)
        if path := path_data(line.coords, closed=line.is_ring):
            paths.append(path)
    return "".join(paths), len(paths)


def build():
    land_features = features("ne_110m_land")
    zone_features = features("ne_10m_time_zones")
    land = union_all([shape(feature["geometry"]) for feature in land_features])
    land = land.intersection(FRAME).simplify(SIMPLIFY, preserve_topology=True)
    polygons = list(parts(land, "Polygon"))
    land_d = "".join(path_data(ring.coords, closed=True) for polygon in polygons
                     for ring in (polygon.exterior, *polygon.interiors))
    coast = land.boundary.difference(FRAME.boundary)
    coast_d, coast_count = line_paths(coast)

    # Dissolve same-offset polygons first. Union the resulting linework to draw
    # shared edges once, then drop the artificial draw edges of the viewport.
    offsets = defaultdict(list)
    for feature in zone_features:
        offsets[feature["properties"]["utc_format"]].append(
            shape(feature["geometry"]).intersection(FRAME)
        )
    bounds = union_all([union_all(group).boundary for group in offsets.values()])
    bounds = bounds.difference(FRAME.boundary)
    inland_d, inland_count = line_paths(bounds.intersection(land), SIMPLIFY)
    # Different source scales can place coastal zone lines just offshore. Leave
    # a small clearance so those lines don't read as a second coastline.
    water = FRAME.difference(land.union(coast.buffer(0.24)))
    ocean_d, ocean_count = line_paths(bounds.intersection(water), SIMPLIFY)
    parallels_d = "".join(f"M{project(-180, lat)}H720" for lat in range(-60, 61, 30))

    svg = f'''<svg viewBox="0 0 720 330" class="world-map" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="World map with standard time zone boundaries">
  <metadata>Natural Earth v5.1.2, public domain: ne_110m_land and ne_10m_time_zones. Generated by generate-map.py.</metadata>
  <path class="map-water" fill="#fff" d="M0 0H720V330H0Z"/>
  <path class="map-land" fill="#e4e4e4" fill-rule="evenodd" d="{land_d}"/>
  <g fill="none" stroke-linecap="round" stroke-linejoin="round">
    <path class="map-parallels" stroke="#bdbdbd" stroke-width=".36" d="{parallels_d}"/>
    <path class="map-zone-ocean" stroke="#a5a5a5" stroke-width=".48" stroke-dasharray="1.6 1.45" d="{ocean_d}"/>
    <path class="map-zone-land" stroke="#909090" stroke-width=".51" d="{inland_d}"/>
    <path class="map-coast" stroke="#777" stroke-width=".57" d="{coast_d}"/>
  </g>
  <g id="map-pins"></g>
</svg>
'''
    counts = (f"Land: {len(land_features)} source features, {len(polygons)} clipped polygons, "
              f"{coast_count} coast subpaths. Zones: {len(zone_features)} source features, "
              f"{len(offsets)} UTC offsets, {inland_count} land and {ocean_count} ocean subpaths.")
    return svg, counts


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=ROOT / "src" / "map.svg")
    args = parser.parse_args()
    svg, counts = build()
    args.output.write_text(svg, encoding="utf-8", newline="\n")
    print(counts)
    print(f"{args.output}: {len(svg.encode('utf-8')):,} bytes")


if __name__ == "__main__":
    main()
