#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["shapely==2.1.2"]
# ///
"""Refresh globe-data.js from the project's public-domain Natural Earth v5.1.2 files."""

from collections import defaultdict
import gzip
import json
from pathlib import Path

from shapely import box, union_all
from shapely.geometry import MultiLineString, MultiPolygon, mapping, shape
from shapely.geometry.polygon import orient
from shapely.ops import linemerge

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORLD = box(-180, -90, 180, 90)
TOLERANCE = 0.15


def parts(geometry, kind):
    if geometry.is_empty:
        return
    if geometry.geom_type == kind:
        yield geometry
    elif hasattr(geometry, 'geoms'):
        for child in geometry.geoms:
            yield from parts(child, kind)


def features(name):
    with gzip.open(ROOT / f'{name}.geojson.gz', 'rt', encoding='utf-8') as source:
        return json.load(source)['features']


def lines(geometry):
    merged = linemerge(list(parts(geometry, 'LineString')))
    return MultiLineString([line for line in parts(merged.simplify(TOLERANCE), 'LineString')
                            if line.length >= TOLERANCE])


def round_coords(item):
    if isinstance(item, (tuple, list)):
        return [round_coords(child) for child in item]
    return round(item, 3)


def build():
    # Union the source polygons before clipping; keep the polar regions.
    land = union_all([shape(f['geometry']) for f in features('ne_110m_land')])
    land = land.intersection(WORLD).simplify(TOLERANCE, preserve_topology=True)
    coast = land.boundary.difference(WORLD.boundary)
    # D3's spherical path expects clockwise exterior rings for small polygons.
    polygons = MultiPolygon([orient(p, sign=-1) for p in parts(land, 'Polygon')])
    offsets = defaultdict(list)
    for feature in features('ne_10m_time_zones'):
        offsets[feature['properties']['utc_format']].append(shape(feature['geometry']))
    bounds = union_all([union_all(group).boundary for group in offsets.values()])
    bounds = bounds.intersection(WORLD).difference(WORLD.boundary)
    # Preserve a small clearance from the coast where source scales disagree.
    water = WORLD.difference(land.union(coast.buffer(0.24)))
    # The antimeridian closes the nominal UTC band layout. Use two segments
    # rather than a pole-to-pole segment (the latter is spherically ambiguous).
    offshore = list(parts(bounds.intersection(water), 'LineString'))
    offshore.extend(parts(MultiLineString([[(180, -90), (180, 0), (180, 90)]]).intersection(water), 'LineString'))
    layers = {'land': polygons, 'coast': lines(coast), 'zoneLand': lines(bounds.intersection(land)),
              'zoneWater': lines(MultiLineString(offshore))}
    return {key: {'type': layer.geom_type, 'coordinates': round_coords(mapping(layer)['coordinates'])}
            for key, layer in layers.items()}


if __name__ == '__main__':
    output = HERE / 'globe-data.js'
    data = json.dumps(build(), separators=(',', ':'))
    output.write_text('// Generated by generate-geometry.py. Natural Earth v5.1.2, public domain.\n'
                      f'window.AlmanacGlobeData={data};\n', encoding='utf-8')
    print(f'{output.name}: {output.stat().st_size:,} bytes')
